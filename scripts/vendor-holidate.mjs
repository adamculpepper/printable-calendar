/**
 * Vendors the `holidate` npm package into vendor/holidate/holidate.js as a
 * browser-loadable ES module.
 *
 * The app itself has no build step and loads no CDN scripts, but holidate ships
 * as CommonJS split across three files. Rather than hand-copying (and silently
 * drifting from upstream), this script reads whatever npm installed and wraps
 * the sources verbatim in a tiny CommonJS shim. Re-run it after bumping the
 * dependency:
 *
 *   npm install && npm run vendor
 *
 * Upstream: https://github.com/zachnology/holidate (MIT)
 */

import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const packageRoot = resolve(repoRoot, 'node_modules/holidate');
const outputPath = resolve(repoRoot, 'vendor/holidate/holidate.js');

/**
 * Files are listed leaf-first so the generated bundle registers dependencies
 * before the modules that require them. The `id` is the basename that
 * `resolveModuleId` below will produce for any require() specifier pointing at
 * that file, which is what lets the shim stay path-agnostic.
 */
const sourceFiles = [
  { id: 'util', path: 'src/util.js' },
  { id: 'us.service', path: 'src/localization/us.service.js' },
  { id: 'holidate', path: 'src/holidate.js' },
];

function indentBody(source) {
  return source
    .replace(/\r\n/g, '\n')
    .trimEnd()
    .split('\n')
    .map((line) => (line.length ? `    ${line}` : line))
    .join('\n');
}

function readPackageVersion() {
  const manifest = JSON.parse(readFileSync(resolve(packageRoot, 'package.json'), 'utf8'));
  return manifest.version;
}

const modules = sourceFiles.map((file) => {
  const source = readFileSync(resolve(packageRoot, file.path), 'utf8');
  return {
    ...file,
    source,
    sha256: createHash('sha256').update(source).digest('hex').slice(0, 16),
  };
});

const version = readPackageVersion();

const provenance = modules
  .map((module) => ` *   ${module.path.padEnd(32)} sha256:${module.sha256}`)
  .join('\n');

const registrations = modules
  .map(
    (module) => `__define('${module.id}', function (module, exports, require) {\n${indentBody(module.source)}\n});`
  )
  .join('\n\n');

const bundle = `/**
 * holidate ${version} - vendored, do not edit by hand.
 *
 * Generated by scripts/vendor-holidate.mjs from the npm package. The module
 * bodies below are byte-for-byte upstream; only the CommonJS wrapper around
 * them is ours.
 *
${provenance}
 *
 * Copyright (c) Zach Ledbetter and holidate contributors. Released under the
 * MIT License; see vendor/holidate/LICENSE.md.
 * https://github.com/zachnology/holidate
 */

const registry = new Map();

/**
 * holidate's internal require() calls use relative paths ('../util',
 * './localization/us.service'). Every filename in the package is unique, so
 * collapsing a specifier down to its extensionless basename resolves it
 * without needing a path-aware module loader.
 */
function resolveModuleId(specifier) {
  return specifier.split('/').pop().replace(/\\.js$/, '');
}

function __define(id, factory) {
  registry.set(id, { factory, module: null });
}

function __require(specifier) {
  const id = resolveModuleId(specifier);
  const entry = registry.get(id);

  if (!entry) {
    throw new Error(\`holidate: cannot resolve module "\${specifier}"\`);
  }

  if (!entry.module) {
    entry.module = { exports: {} };
    entry.factory(entry.module, entry.module.exports, __require);
  }

  return entry.module.exports;
}

${registrations}

export const { getHolidays } = __require('holidate');
export const HOLIDATE_VERSION = '${version}';
export default { getHolidays, HOLIDATE_VERSION };
`;

mkdirSync(dirname(outputPath), { recursive: true });
writeFileSync(outputPath, bundle, 'utf8');

const licenseSource = resolve(packageRoot, 'LICENSE.md');
writeFileSync(
  resolve(dirname(outputPath), 'LICENSE.md'),
  readFileSync(licenseSource, 'utf8'),
  'utf8'
);

console.log(`Vendored holidate ${version} -> ${outputPath}`);
for (const module of modules) {
  console.log(`  ${module.path} (sha256:${module.sha256})`);
}
